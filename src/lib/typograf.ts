/**
 * Типограф Mirror: короткие слова не остаются в конце строки (правило пользователя, дизайн-система, раздел 10).
 * — слово из 1–3 символов (предлог, союз, частица, число, «№1») связывается со следующим неразрывным пробелом;
 * — тире связывается с предыдущим словом.
 * Применяется к строкам из src/content, поэтому на клиент уходит уже готовый текст.
 */
const NBSP = "\u00a0"
const SHORT_WORD = /(^|[\s\u00a0(«"„—–/])([A-Za-zА-Яа-яЁё0-9№]{1,3}) +(?=\S)/g
const DASH = / +([—–])/g

export function typograf(text: string): string {
  let out = text
  let prev: string
  // Цепочки «и в отчёте»: после первой замены следующее короткое слово тоже должно связаться
  do {
    prev = out
    out = out.replace(SHORT_WORD, `$1$2${NBSP}`)
  } while (out !== prev)
  return out.replace(DASH, `${NBSP}$1`)
}
