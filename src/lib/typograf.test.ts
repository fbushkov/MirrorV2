import { describe, expect, it } from "vitest"
import { typograf } from "./typograf"

const show = (s: string) => s.replaceAll(" ", "⍽")

describe("typograf", () => {
  it("связывает предлоги и союзы со следующим словом", () => {
    expect(show(typograf("сверяет то, что компания обещает сотрудникам и кандидатам, с отзывами"))).toBe(
      "сверяет то, что⍽компания обещает сотрудникам и⍽кандидатам, с⍽отзывами",
    )
  })

  it("связывает числа и номера", () => {
    expect(show(typograf("от 5 человек, 3 рабочих дня, Шаг №1 готов"))).toBe("от⍽5⍽человек, 3⍽рабочих дня, Шаг⍽№1⍽готов")
  })

  it("держит вместе цепочку коротких слов", () => {
    expect(show(typograf("видно и в отчёте"))).toBe("видно и⍽в⍽отчёте")
  })

  it("не даёт тире начать строку", () => {
    expect(show(typograf("Рутину — собрать"))).toBe("Рутину⍽— собрать")
  })

  it("не трогает длинные слова и конец строки", () => {
    expect(typograf("Индекс культуры")).toBe("Индекс культуры")
    expect(show(typograf("ответ да"))).toBe("ответ да")
  })

  it("идемпотентен", () => {
    const once = typograf("Срез — 3 рабочих дня и в отчёте")
    expect(typograf(once)).toBe(once)
  })
})
