export function pulseLevel(score: number): "ok" | "warn" | "bad" {
  if (score >= 65) return "ok"
  if (score >= 50) return "warn"
  return "bad"
}
export const LEVEL_LABEL = { ok: "в норме", warn: "внимание", bad: "риск" } as const

/** Индекс переживаемой культуры — среднее по 10 метрикам */
