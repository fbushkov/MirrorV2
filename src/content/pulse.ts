export function normScore(metrics: string[]) {
  const ms = PULSE_METRICS.filter((m) => metrics.includes(m.id))
  return Math.round(ms.reduce((s, m) => s + m.score, 0) / ms.length)
}

export const PULSE_GAP = (() => {
  const levels = CULTURE_CODE.map((c) => pulseLevel(normScore(c.metrics)))
  return { diverge: levels.filter((l) => l === "bad").length, partial: levels.filter((l) => l === "warn").length, total: CULTURE_CODE.length }
})()

