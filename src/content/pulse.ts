/** Вклад каналов в балл метрики, % (опросы / тексты / поведенческие данные) */
export function channelMix(id: string) {
  const n = id.length
  const o = 45 + (n % 4) * 5
  const tt = 30 - (n % 3) * 5
  return { o, t: tt, p: 100 - o - tt }
}

